/**
 * Turbopack loader: removes the OpenAPI-only layer from src/lib/contract/*
 * for every application bundle (client AND server).
 *
 * The contract files are the single source of truth for two things at once:
 * the runtime Zod schemas the app validates with, and the documentation
 * that becomes openapi.json for the backend team. Keeping the prose next to
 * the field it describes is what stops it drifting - but the app never
 * reads any of it, and it was costing ~5 KB gzip on every page (including
 * the public proof page). This strips it at build time instead of
 * splitting each file in two and letting the halves drift apart.
 *
 * It removes, and only removes:
 *   1. `.openapi(...)` calls           -> the receiver they were called on
 *   2. `extensibleEnum(values, prose)` -> `extensibleEnum(values)`
 *   3. `import "./zod-openapi-setup"`  (the side-effect import that installs
 *                                       `.openapi`, and drags zod-to-openapi in)
 *   4. `export function register*Paths` (path registration: prose plus the
 *                                       request/response docs, used only by
 *                                       scripts/generate-openapi.ts)
 * Everything else - every schema, every check, every runtime message - is
 * left byte-for-byte. openapi.json is generated by tsx from the UNSTRIPPED
 * sources (scripts/generate-openapi.ts), so it is unaffected; and
 * scripts/check-contract-prose.mjs fails CI if any description from it
 * still appears in the built bundle, so a pattern this loader doesn't
 * understand can't silently reintroduce the cost.
 */
const ts = require("typescript");

module.exports = function openapiStripLoader(source) {
  const sf = ts.createSourceFile(
    this.resourcePath,
    source,
    ts.ScriptTarget.Latest,
    /* setParentNodes */ true,
    ts.ScriptKind.TS,
  );

  const isOpenapiCall = (n) =>
    ts.isCallExpression(n) &&
    ts.isPropertyAccessExpression(n.expression) &&
    n.expression.name.text === "openapi";

  const isExtensibleEnumCall = (n) =>
    ts.isCallExpression(n) &&
    ts.isIdentifier(n.expression) &&
    n.expression.text === "extensibleEnum";

  const isStrippedStatement = (s) => {
    if (
      ts.isImportDeclaration(s) &&
      !s.importClause &&
      ts.isStringLiteral(s.moduleSpecifier) &&
      s.moduleSpecifier.text.endsWith("zod-openapi-setup")
    ) {
      return true;
    }
    return (
      ts.isFunctionDeclaration(s) &&
      s.name !== undefined &&
      /^register\w*Paths$/.test(s.name.text)
    );
  };

  // The text of `node` from its first token to its last, with the layer
  // above removed from anywhere inside it.
  function render(node) {
    if (isOpenapiCall(node)) return render(node.expression.expression);

    if (isExtensibleEnumCall(node) && node.arguments.length > 1) {
      const callee = render(node.expression);
      return `${callee}(${render(node.arguments[0])})`;
    }

    const children = node.getChildren(sf);
    if (children.length === 0)
      return source.slice(node.getStart(sf), node.getEnd());

    let out = "";
    let pos = node.getStart(sf);
    for (const child of children) {
      const start = child.getStart(sf);
      out += source.slice(pos, start) + render(child);
      pos = child.getEnd();
    }
    return out + source.slice(pos, node.getEnd());
  }

  let out = "";
  let pos = 0;
  for (const statement of sf.statements) {
    const start = statement.getFullStart();
    out += source.slice(pos, start);
    if (!isStrippedStatement(statement)) {
      out += source.slice(statement.getFullStart(), statement.getStart(sf));
      out += render(statement);
    }
    pos = statement.getEnd();
  }
  out += source.slice(pos);
  return out;
};
